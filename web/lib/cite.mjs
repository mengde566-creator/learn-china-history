/**
 * 「这一句出自哪儿」——依据面板和「原文」面板显示给读者的那一行字。
 *
 * **为什么单独一个文件。** 这条规则原来只写在 `build-content.mjs` 里，
 * `new-story.mjs` 自己算了一份不一样的。后果是：新加的闸门要求
 * 「引了小说就得写出书名」，而骨架生成器生成出来的正是闸门要拦的形状——
 * **`npm run new-story` 生成的文件，第一次 `npm run check` 就红。**
 * 「加一篇故事」这条主干道被自己堵死，报错还指向生成器刚写的东西。
 * 同一个词在两个脚本里含义不同，本身就是隐患；放这里两边引用，
 * 就不存在「改了一边忘了另一边」。
 *
 * 三档的写法本来就不一样，因为它们的出处本来就不一样：
 *
 *   正史  出处就是这本书本身          → 《三国志·魏书·武帝纪》正文
 *   注    裴松之引的**别的书**        → 裴松之注引孙盛《异同杂语》
 *   小说  出处是「第几回」这种细目    → 《三国演义》第四回
 *   野史  同小说                      → 《曹瞒传》卷上
 *
 * 正史和注不用接书名：前者的 note 本来就是整本书名，后者写出来自带书名。
 * 小说和野史要接——「第四回」单看不知道是谁的第四回，读者没法判断该不该信。
 */

/** 比书名在不在的时候把书名号和空白都去掉，免得「《三国演义》」和「三国演义」比不出相等 */
const bare = (s) => String(s || '').replace(/[《》〈〉\s]/g, '')

/**
 * @param {{tier?: string, book?: string, note?: string|null}} e
 *   tier  底本档次（正史 / 注 / 小说 / 野史）
 *   book  底本小节里那个书名，例如「《三国演义》」「《三国志·魏书·武帝纪》正文」
 *   note  这一条自己的出处（四列表的「出处」栏），例如「第四回」
 * @returns {string} 显示给读者的出处字符串
 */
export function citeOf({ tier, book, note } = {}) {
  const b = String(book || '')
  const o = String(note || '').trim() || b
  if (!o) return ''
  if (tier !== '小说' && tier !== '野史') return o
  if (!b) return o
  /* 已经带了书名就别再接一遍。写「三国演义第四回」（少书名号）也算带了——
     原来是严格子串比，那种写法会拼成「《三国演义》三国演义第四回」原样印出去。 */
  return bare(o).includes(bare(b)) ? o : `${b}${o}`
}
